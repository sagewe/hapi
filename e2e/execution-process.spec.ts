import { expect, test } from '@playwright/test'

for (const agent of ['codex', 'agy']) {
    test(`${agent}: live prose stays ordered between collapsed tool groups`, async ({ page }) => {
        await page.goto(`/e2e-fixtures/execution-process-fixture.html?agent=${agent}&concurrent=1`)
        await expect(page.getByTestId('execution-timing')).toContainText('Running for')
        await expect(page.getByTestId('chat-response-feedback')).toHaveCount(0)
        await expect(page.getByTestId('execution-tools')).toHaveCount(3)
        await expect(page.getByText('Inspecting the fixture.', { exact: true })).toBeVisible()
        await expect(page.getByText('Checking parallel results.', { exact: true })).toBeVisible()
        await expect(page.getByText('Checking the result.', { exact: true })).toBeVisible()
        await expect(page.getByTestId('execution-activity')).toHaveCount(0)
        await page.getByRole('button', { name: 'Complete turn' }).click()
        const process = page.getByTestId('execution-process')
        await expect(process).toHaveCount(1)
        await expect(page.getByTestId('execution-tools')).toHaveCount(0)
        await expect(process.locator(':scope > button')).toContainText('Took')
        await expect(process.locator(':scope > button')).not.toContainText('error')
        await process.locator(':scope > button').click()
        await expect(process.getByRole('button', { name: /echo failed-check/ })).toHaveCount(0)
        await process.getByTestId('execution-detail-group').first().click()
        await expect(process.getByRole('button', { name: /echo failed-check/ })).toBeVisible()
        await expect(page.getByText('Final answer stays visible.', { exact: true })).toBeVisible()
    })
    test(`${agent}: completion folds intermediate prose but not answer paragraphs`, async ({ page }) => {
        await page.goto(`/e2e-fixtures/execution-process-fixture.html?agent=${agent}`)
        await expect(page.getByText('Inspecting the fixture.', { exact: true })).toBeVisible()
        await expect(page.getByText('Checking the result.', { exact: true })).toBeVisible()
        await page.getByRole('button', { name: 'Complete turn' }).click()
        await expect(page.getByText('Inspecting the fixture.', { exact: true })).toHaveCount(0)
        await expect(page.getByTestId('execution-process').locator(':scope > button')).toHaveAttribute('aria-expanded', 'false')
        await expect(page.getByText('Final answer stays visible.', { exact: true })).toBeVisible()
        await page.getByRole('button', { name: 'Add paragraph' }).click()
        await expect(page.getByText('Additional final paragraph.', { exact: true })).toBeVisible()
        await expect(page.getByText('Final answer stays visible.', { exact: true })).toBeVisible()
    })
    test(`${agent}: reading an expanded group prevents completion from collapsing the timeline`, async ({ page }) => {
        await page.goto(`/e2e-fixtures/execution-process-fixture.html?agent=${agent}`)
        const toggle = page.getByTestId('execution-tools').first().locator(':scope > button')
        await toggle.click()
        const before = (await toggle.boundingBox())!.y
        await page.getByRole('button', { name: 'Complete turn' }).click()
        await expect(toggle).toHaveAttribute('aria-expanded', 'true')
        await expect(page.getByTestId('execution-timing')).toContainText('Took')
        await expect(page.getByText('Final answer stays visible.', { exact: true })).toBeVisible()
        expect(Math.abs((await toggle.boundingBox())!.y - before)).toBeLessThan(2)
        await expect(page.getByText('Inspecting the fixture.', { exact: true })).toBeVisible()
    })
    test(`${agent}: inspecting the current step survives the final answer`, async ({ page }) => {
        await page.goto(`/e2e-fixtures/execution-process-fixture.html?agent=${agent}`)
        await page.getByTestId('execution-tools').last().locator(':scope > button').click()
        const activity = page.locator('[data-execution-step="current-check"]')
        await activity.getByRole('button').first().click()
        const dialog = page.getByRole('dialog')
        await expect(dialog).toHaveCount(0)
        await page.getByRole('button', { name: 'View full details', exact: true }).click()
        await expect(dialog).toBeVisible()
        const before = (await activity.boundingBox())!.y
        await page.evaluate(() => (window as unknown as { completeProcess: () => void }).completeProcess())
        await expect(dialog).toBeVisible()
        await dialog.getByRole('button', { name: 'Close', exact: true }).click()
        await expect(dialog).toHaveCount(0)
        await expect(page.getByText('Final answer stays visible.', { exact: true })).toBeVisible()
        expect(Math.abs((await activity.boundingBox())!.y - before)).toBeLessThan(2)
        await expect(page.getByText('Final answer stays visible.', { exact: true })).toBeVisible()
    })
    test(`${agent}: a failed step retains its open inspector`, async ({ page }) => {
        await page.goto(`/e2e-fixtures/execution-process-fixture.html?agent=${agent}`)
        await page.getByTestId('execution-tools').last().locator(':scope > button').click()
        await page.locator('[data-execution-step="current-check"]').getByRole('button').first().click()
        const dialog = page.getByRole('dialog')
        await expect(dialog).toHaveCount(0)
        await page.getByRole('button', { name: 'View full details', exact: true }).click()
        await expect(dialog).toBeVisible()
        await page.evaluate(() => (window as unknown as { failProcess: () => void }).failProcess())
        await expect(dialog).toBeVisible()
        await dialog.getByRole('button', { name: 'Close', exact: true }).click()
        await expect(dialog).toHaveCount(0)
        await expect(page.getByText('Final answer stays visible.', { exact: true })).toBeVisible()
    })
}
